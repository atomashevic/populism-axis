test_that("single and named character vectors remain Python sequences", {
  fixture <- .pa_fixture_module()
  s <- define_scale("trust", positive = c(named = "Јавне установе делују правично."),
                    contrast = "Јавне установе поступају неправично.")
  expect_identical(s$identity, reticulate::py_to_r(fixture$reference()$scale$identity))
  expect_length(summary(s)$components[[1]]$positive, 1)
  expect_false(summary(s)$validated_preset)
  expect_match(summary(s)$hypothesis_selection, "axis alignment")
  f <- define_scale("trust", positive = factor("Јавне установе делују правично."), contrast = factor("Јавне установе поступају неправично."))
  expect_identical(f$identity, s$identity)
  expect_error(define_scale("bad", positive = c("good", NA_character_), contrast = "bad"), "missing")
  expect_error(define_scale("bad", positive = factor(NA_character_), contrast = "bad"), "missing")
  expect_error(define_scale("bad", positive = 123, contrast = "bad"), "character")
})

