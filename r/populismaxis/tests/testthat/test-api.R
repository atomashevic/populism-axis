test_that("durable objects save and reload singleton poles without Python pointers", {
  fixture <- .pa_fixture_module()
  ref <- .pa_fixture_reference(fixture)
  path <- tempfile(fileext = ".json")
  save_reference(ref, path)
  restored <- load_reference(path)
  expect_identical(restored$identity, ref$identity)
  expect_error(save_reference(ref, path), "FileExistsError")
  save_reference(ref, path, overwrite = TRUE)
  native <- tempfile(fileext = ".rds")
  saveRDS(ref, native)
  restored <- readRDS(native)
  expect_identical(restored$identity, ref$identity)
  expect_identical(summary(restored)$inputs$n_windows, 3000000001)
  expect_false(summary(restored)$scale$validated_preset)
  expect_match(summary(restored)$scale$hypothesis_selection, "axis alignment")
  expect_true(all(vapply(unclass(restored), is.character, logical(1))))
  rule <- make_classifier(restored, threshold = 0, below = "ниже", at_or_above = "више")
  save_classifier(rule, path, overwrite = TRUE)
  expect_identical(load_classifier(path)$identity, rule$identity)
  s <- define_scale("single", positive = "High claim.", contrast = "Low claim.")
  save_scale(s, path, overwrite = TRUE)
  expect_identical(load_scale(path)$identity, s$identity)
})

