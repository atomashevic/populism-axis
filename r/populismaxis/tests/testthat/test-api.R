test_that("threshold equality, mismatch and output collisions share Python behavior", {
  fixture <- .pa_fixture_module()
  ref <- .pa_fixture_reference(fixture); result <- .pa_fixture_result(fixture)
  rule <- make_classifier(ref, threshold = 0, below = "ниже", at_or_above = "више")
  labeled <- apply_classifier(rule, result)
  expect_identical(labeled$scores$trust__label, c("ниже", "више", "више"))
  expect_identical(result$scores$trust, labeled$scores$trust)
  expect_error(apply_classifier(rule, labeled), "already exists")
  wrong <- .pa_test_internal(".pa_wrap")(.pa_test_internal(".pa_module")()$ThresholdRule(
    definition_identity = reticulate::py_to_r(fixture$reference()$scale$identity),
    reference_identity = "other-reference", score = "trust", threshold = 0, below = "low", at_or_above = "high"), "classifier")
  expect_error(apply_classifier(wrong, result), "mismatch")
  expect_error(make_classifier(ref, NaN, "low", "high"), "finite")
  expect_error(make_classifier(ref, 0, "same", "same"), "distinct")
  expect_error(make_classifier(ref, 0, "low", "high", score = "missing"), "unavailable")
  out <- tempfile(); dir.create(out)
  writeLines("preserve", file.path(out, "unrelated.txt"))
  write_scores(result, out)
  expect_error(write_scores(labeled, out), "FileExistsError")
  write_scores(labeled, out, overwrite = TRUE)
  expect_identical(readLines(file.path(out, "unrelated.txt")), "preserve")
  csv <- read.csv(file.path(out, "scores.csv"), colClasses = c(id = "character"), check.names = FALSE, na.strings = NULL, encoding = "UTF-8")
  expect_identical(csv$id, c("001", "NA", "ж"))
})

test_that("fitting, scoring and CSV adapters preserve vector and option types with mocked models", {
  fixture <- .pa_fixture_module()
  models <- fixture$MockModels(); models$start(); on.exit(models$stop(), add = TRUE)
  scale <- define_scale("orientation", positive = "Public institutions act fairly.", contrast = "Public institutions act unfairly.")
  texts <- paste("Reference document", seq_len(30), "describes public institutions.")
  ref <- fit_reference(texts, scale = scale, unit = "sentence", threads = 4)
  expect_identical(summary(ref)$settings$claim_check, FALSE)
  one <- score_texts(c(named = "Public bodies serve citizens."), ref, ids = factor("001"), threads = 4)
  expect_identical(one$scores$id, "001")
  batch <- score_texts(c("Public bodies serve citizens.", "Officials betray citizens."), ref, ids = c("001", "NA"))
  expect_identical(batch$scores$id, c("001", "NA"))
  expect_equal(one$scores$orientation, batch$scores$orientation[1], tolerance = 1e-14)
  default <- score_texts("Public bodies serve citizens.", ref)
  expect_identical(default$scores$id, "0")
  expect_error(score_texts(NA_character_, ref), "missing")
  expect_error(score_texts("text", ref, ids = NA_character_), "missing")
  expect_error(score_texts("text", ref, ids = 1), "character")
  expect_error(score_texts(c("one", "two"), ref, ids = c("x", "x")), "unique")
  expect_error(score_texts("text", ref, threads = 1.5), "whole number")
  expect_error(score_texts("text", ref, clean = NA), "TRUE or FALSE")
  expect_error(score_texts("text", ref, unit = "speech"), "Reference was fitted")
  input <- tempfile(fileext = ".csv")
  writeLines(c("id,text", "001,Public bodies serve citizens.", "NA,Officials betray citizens."), input)
  result <- score_csv(input, ref, id_column = "id", threads = 4)
  expect_identical(result$scores$id, c("001", "NA"))
  expect_equal(result$scores$orientation, batch$scores$orientation, tolerance = 0)
  writeLines(c("id,text", paste0(seq_len(30), ",", texts)), input)
  csv_ref <- fit_reference_csv(input, scale, id_column = "id", unit = "sentence", threads = 4)
  expect_equal(score_texts("Public bodies serve citizens.", csv_ref)$scores$orientation, one$scores$orientation, tolerance = 0)
  expect_error(score_csv(input, ref, unsupported = 1), "supported argument")
})
